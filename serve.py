"""
Inference server: wraps the trained colourise U-Net model in an HTTP API with FastAPI.

Endpoints:
    POST /colourise  Upload an image and get a colourised PNG back.
                     Default: side by side - stretched model output (left) vs full-res trick (right).
                     ?full_res=false: the raw 32x32 model output.
    GET  /health     Server status, device (CPU/GPU) and model parameter count.
    GET  /docs       Interactive API docs (generated by FastAPI).

Run:
    uvicorn serve:app --port 8000
    then open http://localhost:8000/docs

Config:
    MODEL_PATH  Path to the trained weights (default: checkpoints/best_model.pt)
"""

import io
import os
import time
from contextlib import asynccontextmanager

import torch
from fastapi import FastAPI, HTTPException, UploadFile
from pathlib import Path
from fastapi.responses import FileResponse, Response
from PIL import Image, UnidentifiedImageError
from torchvision.transforms.functional import pil_to_tensor, to_pil_image

from model import ColouriserUNet

MODEL_PATH = os.getenv("MODEL_PATH", "checkpoints/best_model.pt")
MAX_UPLOAD_BYTES = 5 * 1024 * 1024  # reject uploads over 5 MB
MAX_PIXELS = 4096 * 4096            # reject huge images before decoding them fully
MODEL_INPUT_SIZE = 32                     # the model was trained on 32x32 CIFAR-10 images

state = {}  # holds the model so it is loaded once, not on every request


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Runs once at startup: load the weights and put the model in inference mode."""
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = ColouriserUNet().to(device) # builds the U-Net model with random weights and moves it to device
    model.load_state_dict(torch.load(MODEL_PATH, map_location=device, weights_only=True)) # replaces the random weights with the trained ones
    model.eval()  # switches to inference mode
    state.update(model=model, device=device) # stores the model and device in the state dictionary
    
    yield # open: so the server can run and handle requests
    state.clear() # closing (when you press Ctrl+C): clears the state dictionary when the server shuts down, freeing memory

# Create the web app with a title and version number
app = FastAPI(title="colourise-net", version="1.0.0", lifespan=lifespan)


def colourise_image(img: Image.Image, full_res: bool) -> Image.Image:
    """Greyscale image in, colour image out.
    full_res=False: the raw 32x32 model output
    full_res=True:  side by side - stretched (left) vs full-res trick (right)
    """
    # Greyscale = brightness only. This is also the sharp Y (brightness) layer used in the full-res trick below
    grey = img.convert("L")

    # Shrink to 32x32, the size the model was trained on
    grey_shrunk = grey.resize((MODEL_INPUT_SIZE, MODEL_INPUT_SIZE), Image.BICUBIC)

    # Convert to a tensor, scale pixels from 0-255 to 0-1 (matching training), and add a batch dimension
    # [1, 1, 32, 32] = [batch, channels, height, width] - 1 image, 1 channel (greyscale), 32x32 pixels
    x = pil_to_tensor(grey_shrunk).float().div(255).unsqueeze(0).to(state["device"])

    # Run the model
    with torch.inference_mode():  # no gradient tracking: faster and uses less memory
        # Run the model, take the single image out of the batch, and move it to the CPU
        # Result: [3, 32, 32] = red, green and blue grids, 32x32 pixels, each value between 0 and 1
        pred = state["model"](x)[0].cpu()

    # Convert the model's output from a tensor into a PIL image
    colour_shrunk = to_pil_image(pred)
    if not full_res:
        return colour_shrunk

    # Stretched: simply enlarge the model's 32x32 output to the original size (blurry)
    stretched = colour_shrunk.resize(grey.size, Image.BICUBIC)

    # Full-res trick:
    # YCbCr splits an image into Y (brightness/detail), Cb (blue-yellow) and Cr (red-green).
    # Eyes see detail through brightness, so: sharp Y from the original + colour from the model.
    _, cb, cr = stretched.convert("YCbCr").split()                   # drop model's blurry Y (_), keep colour (Cb, Cr)
    full = Image.merge("YCbCr", (grey, cb, cr)).convert("RGB")       # Y = grey (original, sharp) + model's colour

    # Side by side on one canvas: stretched (left), full-res trick (right)
    comparison = Image.new("RGB", (grey.width * 2, grey.height))
    comparison.paste(stretched, (0, 0))
    comparison.paste(full, (grey.width, 0))
    return comparison

@app.get("/", include_in_schema=False)
def root():
    """Simple upload page for trying the model in the browser."""
    return FileResponse(Path(__file__).parent / "static" / "index.html")

@app.get("/health")
def health():
    """Liveness/readiness check for Docker, load balancers or Kubernetes."""
    model = state.get("model")
    return {
        "status": "ok" if model else "loading",
        "device": state.get("device"),
        "parameters": sum(p.numel() for p in model.parameters()) if model else None,
    }

@app.post("/colourise", responses={200: {"content": {"image/png": {}}}})
async def colourise(file: UploadFile, full_res: bool = True):
    """Upload an image. Default: stretched vs full-res side by side. full_res=false: raw 32x32 model output."""
    # Read at most 5 MB + 1 byte: if we got the extra byte, the file is too big
    data = await file.read(MAX_UPLOAD_BYTES + 1)
    if len(data) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "File too large (max 5 MB)")

    # Check it's a real image, and not too big, before doing any work
    try:
        img = Image.open(io.BytesIO(data))  # only reads the header (cheap)
        if img.width * img.height > MAX_PIXELS:
            raise HTTPException(413, "Image dimensions too large")
        img.load()  # now decode the full image
    except (UnidentifiedImageError, OSError):
        raise HTTPException(415, "Could not read file as an image")

    # Run the model and time it
    start = time.perf_counter()
    result = colourise_image(img, full_res)
    elapsed_ms = (time.perf_counter() - start) * 1000

    # Save the result as a PNG in memory and send it back
    buf = io.BytesIO()
    result.save(buf, format="PNG")
    return Response(
        buf.getvalue(),
        media_type="image/png",
        headers={"X-Inference-Time-Ms": f"{elapsed_ms:.1f}"},
    )